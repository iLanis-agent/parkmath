import json, math

def t(s):
    h, m = int(s[:2]), int(s[3:5])
    assert len(s) == 5 and s[2] == ":" and h <= 23 and m <= 59
    return h * 60 + m

def hm(m):
    h, mi = (m // 60) % 24, m % 60
    ap = "AM" if h < 12 else "PM"
    h12 = 12 if h % 12 == 0 else h % 12
    return f"{h12}:{str(mi).zfill(2)} {ap}"

def pl(n, one, many): return f"{n}{one if n == 1 else many}"
def m(c): return f"${c//100}.{str(c%100).zfill(2)}"

def dur(minutes):
    h, mi = divmod(minutes, 60)
    if h == 0: return pl(mi, " minute", " minutes")
    if mi == 0: return pl(h, " hour", " hours")
    return pl(h, " hour", " hours") + " and " + pl(mi, " minute", " minutes")

def stay(entry, exit_):
    e, x = t(entry), t(exit_)
    assert x > e
    return x - e

def fee(s, g, f, k, pk, d):
    if s <= g: return 0
    u = f if s <= 60 else f + math.ceil((s - 60) / k) * pk
    return min(u, d)

def stay_t(entry, exit_):
    return f"From {hm(t(entry))} to {hm(t(exit_))} the stay is {dur(stay(entry, exit_))}."

def grace_t(entry, exit_, grace):
    s, g = stay(entry, exit_), int(grace)
    if g == 0: return f"With no grace the whole stay is billed from {hm(t(entry))}."
    if s <= g: return f"The stay sits inside the {pl(g,' minute',' minutes')} of grace, so nothing is billed."
    return f"Past the {pl(g,' minute',' minutes')} of grace the whole stay is billed, not the {dur(s-g)} after it."

def fee_t(entry, exit_, grace, first, kmin, kprice, dmax):
    s = stay(entry, exit_)
    g, f, k, pk, d = int(grace), int(first), int(kmin), int(kprice), int(dmax)
    if s <= g: return f"Inside the grace the stay is free: {m(0)}."
    u = f if s <= 60 else f + math.ceil((s - 60) / k) * pk
    if s <= 60 and f >= d: return f"The {m(d)} daily maximum cuts even the first hour to {m(d)}."
    if s <= 60: return f"The stay fits the first hour: {m(f)}, under the {m(d)} daily maximum."
    pre = f"At {m(f)} for the first hour and {m(pk)} for each started block of {pl(k,' minute',' minutes')} after it, the stay bills {m(u)}"
    if u <= d: return pre + f", under the {m(d)} daily maximum."
    return pre + f", so the {m(d)} daily maximum cuts it to {m(d)}."

def leave_t(entry, exit_, grace, first, kmin, kprice, dmax):
    s = stay(entry, exit_)
    g, f, k, pk, d = int(grace), int(first), int(kmin), int(kprice), int(dmax)
    e = t(entry)
    cur = fee(s, g, f, k, pk, d)
    if s <= g:
        return f"Leave by {hm(e+g)} and the stay is free; a minute longer and it is {m(fee(g+1,g,f,k,pk,d))}."
    u = f if s <= 60 else f + math.ceil((s - 60) / k) * pk
    if u > d: return f"The {m(d)} daily maximum already holds; leave any time before midnight and the price stays {m(d)}."
    be = 60 if s <= 60 else 60 + math.ceil((s - 60) / k) * k
    return f"Leave by {hm(e+be)} and the price stays {m(cur)}; a minute longer and it is {m(fee(be+1,g,f,k,pk,d))}."

